// tokens:build — generates (never hand-edit):
//   src/styles/design-tokens.css   every theme in one file: :root base, one block per theme,
//                                  prefers-color-scheme / prefers-contrast bridges, reduced motion
//   src/styles/tokens.d.ts         union type of every semantic token name (for check:specs and editors)
//   docs/specs/tokens.dtcg.json    resolved semantic values per theme — for MCP list_tokens, Claude Design
//   dist/css/<theme>.css           one standalone file per theme (specs/HANDOFF.md build contract)
//   dist/ts/tokens.d.ts            the same types, shipped with the package
//   dist/figma/tokens.json         Figma Variables mirror: Primitives (no modes) + Semantic (one mode per theme)
// The theme list comes from tokens/themes.config.ts — nothing here is hardcoded per theme.
import { writeFileSync, mkdirSync } from 'node:fs';
import { loadTheme, resolve, cssName, toCss, THEMES, THEME_DEFS, themeById } from './lib/dtcg.mjs';

const root = new URL('../', import.meta.url).pathname;
const HEADER = '/* GENERATED by scripts/tokens-build.mjs from tokens/*.json — do not edit. */\n';

/** Both attributes: data-theme is the scaffold's (docs/TOKENS.md), data-iz-theme the handoff's. */
const selectors = (def, extra = []) => [...extra, `[data-theme='${def.attribute}']`, `[data-iz-theme='${def.attribute}']`].join(',\n');

const decls = (theme, names, indent = '  ') => {
  const { all } = loadTheme(theme);
  return [...names].sort().map((n) => { const r = resolve(all, n); return `${indent}${cssName(n)}: ${toCss(r.type, r.value)};`; }).join('\n');
};

const base = loadTheme('light');
const allNames = [...base.semanticNames].sort();
const durationNames = allNames.filter((n) => n.includes('duration.'));
/** Reduced motion: every duration collapses, so no component repeats the query. */
const reducedMotion = (indent = '    ') => durationNames.map((n) => `${indent}${cssName(n)}: 0ms;`).join('\n');

// ── src/styles/design-tokens.css — all themes, one file
let css = `${HEADER}
/* ${themeById('light').description} */
:root {
${decls('light', allNames)}
  color-scheme: light;
}
`;
for (const def of THEME_DEFS.filter((t) => t.file)) {
  // Only what the theme's extends-chain actually overrides — colour for most themes, colour + type for linen.
  const { themeNames } = loadTheme(def.id);
  css += `
/* ${def.description} */
${selectors(def)} {
${decls(def.id, themeNames)}
  color-scheme: ${def.colorScheme};
}
`;
}
css += `
/* OS bridges apply only when the app has not chosen a theme explicitly. */`;
const bridge = { 'prefers-color-scheme: dark': '(prefers-color-scheme: dark)', 'prefers-contrast: more': '(prefers-contrast: more)', 'prefers-contrast: more and dark': '(prefers-contrast: more) and (prefers-color-scheme: dark)' };
for (const def of THEME_DEFS.filter((t) => t.osBridge)) {
  const { themeNames } = loadTheme(def.id);
  css += `
@media ${bridge[def.osBridge]} {
  :root:not([data-theme]):not([data-iz-theme]) {
${decls(def.id, themeNames, '    ')}
    color-scheme: ${def.colorScheme};
  }
}
`;
}
css += `
@media (prefers-reduced-motion: reduce) {
  :root {
${reducedMotion('    ')}
  }
}
`;
writeFileSync(`${root}src/styles/design-tokens.css`, css);

// ── types
const types = `// GENERATED by scripts/tokens-build.mjs — do not edit.\nexport type TokenName =\n${allNames.map((n) => `  | '${n}'`).join('\n')};\nexport type CssVar = \`--iz-\${string}\`;\nexport type ThemeId = ${THEMES.map((t) => `'${t}'`).join(' | ')};\n`;
writeFileSync(`${root}src/styles/tokens.d.ts`, types);
mkdirSync(`${root}dist/ts`, { recursive: true });
writeFileSync(`${root}dist/ts/tokens.d.ts`, types);

// ── dist/css/<theme>.css — one standalone file per theme, usable on its own or via the attribute
mkdirSync(`${root}dist/css`, { recursive: true });
for (const def of THEME_DEFS) {
  const sel = def.attribute === null ? ':root' : selectors(def, [':root']);
  writeFileSync(`${root}dist/css/${def.id}.css`, `${HEADER}/* ${def.description} */
${sel} {
${decls(def.id, allNames)}
  color-scheme: ${def.colorScheme};
}

@media (prefers-reduced-motion: reduce) {
  ${sel.split(',\n').join(',\n  ')} {
${reducedMotion('    ')}
  }
}
`);
}

// ── resolved DTCG snapshot per theme (semantic layer), for Figma / MCP / Claude Design
const snapshot = { $description: 'Resolved semantic tokens per theme. Generated — the source is tokens/*.json.', themes: {} };
for (const theme of THEMES) {
  const t = loadTheme(theme);
  snapshot.themes[theme] = Object.fromEntries(allNames.map((n) => {
    const r = resolve(t.all, n);
    return [n, { $type: r.type, $value: r.value, alias: t.all.get(n).value, css: cssName(n), ...(base.all.get(n).description ? { $description: base.all.get(n).description } : {}) }];
  }));
}
mkdirSync(`${root}docs/specs`, { recursive: true });
writeFileSync(`${root}docs/specs/tokens.dtcg.json`, JSON.stringify(snapshot, null, 2));

// ── dist/figma/tokens.json — Figma Variables mirror (docs/TOKENS.md § Figma mirror).
// Primitives: no modes, raw values. Semantic: one mode per theme, every variable an ALIAS
// (a flattened export is useless for theming), named with "/" as Figma's group separator.
const figmaName = (n) => n.replace(/\./g, '/');
const primitives = Object.fromEntries([...base.primitiveNames].sort().map((n) => {
  const t = base.all.get(n);
  return [figmaName(n), { $type: t.type, $value: t.value, ...(t.description ? { $description: t.description } : {}) }];
}));
const semantic = Object.fromEntries(allNames.map((n) => {
  const modes = Object.fromEntries(THEMES.map((theme) => {
    const t = loadTheme(theme);
    return [themeById(theme).attribute ?? 'light', { alias: figmaName(t.all.get(n).value.replace(/[{}]/g, '')), resolved: resolve(t.all, n).value }];
  }));
  return [figmaName(n), { $type: base.all.get(n).type, modes, ...(base.all.get(n).description ? { $description: base.all.get(n).description } : {}) }];
}));
mkdirSync(`${root}dist/figma`, { recursive: true });
writeFileSync(`${root}dist/figma/tokens.json`, JSON.stringify({
  $description: 'Figma Variables mirror. Primitives: one collection, no modes. Semantic: one collection, one mode per theme, every variable an alias to a Primitive. Generated — see docs/TOKENS.md § Figma mirror.',
  collections: { Primitives: { modes: [], variables: primitives }, Semantic: { modes: THEMES.map((t) => themeById(t).attribute ?? 'light'), variables: semantic } },
}, null, 2));

console.log(`[tokens-build] ${allNames.length} semantic tokens × ${THEMES.length} themes → src/styles/design-tokens.css, tokens.d.ts, docs/specs/tokens.dtcg.json, dist/css/*.css (${THEMES.length}), dist/ts/tokens.d.ts, dist/figma/tokens.json`);
